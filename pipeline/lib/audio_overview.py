AUDIO_JS = r"""
(function () {
  function capability() { return window._AUDIO_CAPABILITY || {state:"UNAVAILABLE", reason:"GEMINI_AUTH_UNAVAILABLE"}; }
  function applyAudioCapability() {
    var c = capability(), button = document.getElementById("audio-open"), notice = document.getElementById("audio-unavailable");
    if (!button) return;
    var ready = c.state === "AVAILABLE";
    button.disabled = !ready;
    button.setAttribute("aria-disabled", String(!ready));
    button.hidden = !ready;
    if (notice) { notice.hidden = ready; notice.textContent = ready ? "" : "Audio Overview unavailable: " + c.reason; }
  }
  window.openAudioModal = function () {
    var c = capability();
    // A6: same discriminated pair the server emits — clients switch on `result`.
    if (c.state !== "AVAILABLE") return {schema:1, result:"FEATURE_UNAVAILABLE", capability:c};
    return {schema:1, result:"PLANNED", capability:c};
  };
  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", applyAudioCapability);
  else applyAudioCapability();
})();
"""


def audio_script_block(_legacy_key=None, mode="paper", ctx=None, provider_js="", local_emails=None,
                       capability: AudioCapabilityV1 | Mapping | None = None):
    """Emit a capability-only script without probing credentials or serializing context."""
    if capability is None:
        capability = configured_audio_capability()
    if isinstance(capability, AudioCapabilityV1):
        capability = capability.to_dict()
    status = json.dumps(capability, ensure_ascii=False, separators=(",", ":"))
    return "<script>window._AUDIO_CAPABILITY=" + status + ";\n" + AUDIO_JS + "</script>"
