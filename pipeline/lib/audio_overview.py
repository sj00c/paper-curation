"""Secret-free, server-routed Audio Overview UI assets.

The browser receives only an informational capability record.  It never receives
provider credentials and never contacts a provider directly.
"""
from __future__ import annotations

from dataclasses import asdict, dataclass
from html import escape
import json
from typing import Mapping

SCRIPT_MODEL = "gemini-3.1-pro-preview"
TTS_MODEL = "gemini-2.5-flash-preview-tts"


@dataclass(frozen=True)
class AudioCapabilityV1:
    schema: str = "AudioCapabilityV1"
    feature: str = "audio_overview"
    provider: str = "gemini"
    state: str = "UNAVAILABLE"
    reason: str = "GEMINI_AUTH_UNAVAILABLE"
    model: str | None = None

    def to_dict(self) -> dict:
        return asdict(self)


def derive_audio_capability(*, auth: str | None, models: Mapping[str, str] | None,
                            safe_root: bool = True) -> AudioCapabilityV1:
    """Derive capability using configuration only; this deliberately has no I/O."""
    if not safe_root:
        return AudioCapabilityV1(reason="AUDIO_TEMP_RECOVERY_AMBIGUOUS")
    if not isinstance(auth, str) or not auth.strip():
        return AudioCapabilityV1(reason="GEMINI_AUTH_UNAVAILABLE")
    models = models or {}
    if (models.get("script") != SCRIPT_MODEL or models.get("tts") != TTS_MODEL):
        return AudioCapabilityV1(reason="GEMINI_MODEL_UNAVAILABLE")
    return AudioCapabilityV1(state="AVAILABLE", reason="READY", model=SCRIPT_MODEL)


def configured_audio_capability(config: Mapping | None = None, *, auth: str | None = None,
                                safe_root: bool = True) -> AudioCapabilityV1:
    """Render unavailable unless the localhost server supplies resolved auth state."""
    if config is None:
        from config_loader import load_config
        config = load_config()
    audio = config.get("audio_overview", {}) if isinstance(config, Mapping) else {}
    models = audio.get("models", {}) if isinstance(audio, Mapping) else {}
    return derive_audio_capability(auth=auth, models=models, safe_root=safe_root)


def audio_plan_status(capability: AudioCapabilityV1) -> dict:
    """Discriminated result for direct Audio planning (A6).

    `result` is REQUIRED on both variants so a client switches on one
    discriminator instead of inferring intent from the absence of a key, and so
    the frozen unknown-key rejection still applies. The unavailable variant is
    non-mutating: no operation, claim, or credential is created and no provider
    client is constructed.
    """
    if capability.state == "AVAILABLE":
        return {"schema": 1, "result": "PLANNED", "capability": capability.to_dict()}
    return {"schema": 1, "result": "FEATURE_UNAVAILABLE", "capability": capability.to_dict()}


